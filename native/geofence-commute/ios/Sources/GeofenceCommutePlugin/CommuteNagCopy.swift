/// 퇴근 독촉 알림 문구 200개.
///
/// - 4단계(퇴근시간 +1시간 / +2시간 / +3시간 / +4시간) × 50개
/// - 하루 4회 알림은 각 단계의 문구 풀에서 **날짜 기반**으로 하나씩 골라
///   매일 다른 문구가 나오고, 50일이면 각 단계의 50개를 한 번씩 모두 쓴다.
/// - 같은 날 4회는 서로 다른 단계에서 고르므로 절대 겹치지 않는다.
enum CommuteNagCopy {
    static let totalCount = 200
    static let roundCount = 4

    static let tiers: [[String]] = [tier1, tier2, tier3, tier4]

    /// 2020-01-01 부터의 일수. 날짜가 하루 넘어가면 항상 1씩 커진다.
    /// (그래서 어제와 오늘은 서로 다른 문구가 나온다.)
    static func dayIndex(for day: String, calendar: Calendar = .current) -> Int {
        let parts = day.split(separator: "-").compactMap { Int($0) }
        guard parts.count == 3 else { return 0 }
        var components = DateComponents()
        components.year = parts[0]
        components.month = parts[1]
        components.day = parts[2]
        guard let date = calendar.date(from: components),
              let reference = calendar.date(from: DateComponents(year: 2020, month: 1, day: 1)) else { return 0 }
        return calendar.dateComponents([.day], from: reference, to: date).day ?? 0
    }

    /// round: 1...4
    static func phrase(day: String, round: Int, calendar: Calendar = .current) -> String {
        let tier = max(0, min(tiers.count - 1, round - 1))
        let pool = tiers[tier]
        guard !pool.isEmpty else { return "" }
        let offset = dayIndex(for: day, calendar: calendar) + round * 13
        let index = ((offset % pool.count) + pool.count) % pool.count
        return pool[index]
    }

    /// 하루치 4개 (1시간차 → 4시간차)
    static func phrases(day: String, calendar: Calendar = .current) -> [String] {
        (1...roundCount).map { phrase(day: day, round: $0, calendar: calendar) }
    }

